-- Secure manager-code claim. The friend supplies only the code.
create or replace function public.claim_manager_code(p_code text)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  inv public.manager_invites;
  tt public.tournament_teams;
begin
  if auth.uid() is null then raise exception 'Sign in first'; end if;
  select * into inv from public.manager_invites where upper(invite_code)=upper(p_code) for update;
  if inv.id is null then raise exception 'Invalid manager code'; end if;
  select * into tt from public.tournament_teams where id=inv.tournament_team_id for update;
  if tt.manager_user_id is not null and tt.manager_user_id <> auth.uid() then raise exception 'This team has already been claimed'; end if;
  update public.tournament_teams set manager_user_id=auth.uid() where id=tt.id;
  update public.manager_invites set claimed_at=coalesce(claimed_at,now()) where id=inv.id;
  return jsonb_build_object('tournament_team_id',tt.id,'tournament_id',tt.tournament_id,'local_team_id',tt.local_team_id,'team_name',tt.team_name);
end $$;
grant execute on function public.claim_manager_code(text) to authenticated;

-- MATCHES: public matches readable by signed-in users; participants can read private matches.
drop policy if exists matches_read on public.matches;
create policy matches_read on public.matches for select to anon, authenticated using (
 visibility='public' or host_user_id=auth.uid() or exists(
   select 1 from public.tournament_teams tt where tt.tournament_id=matches.tournament_id and tt.manager_user_id=auth.uid() and tt.local_team_id in (matches.team_a_local_id,matches.team_b_local_id)
 )
);
drop policy if exists matches_host_insert on public.matches;
create policy matches_host_insert on public.matches for insert to authenticated with check (host_user_id=auth.uid());
drop policy if exists matches_host_update on public.matches;
create policy matches_host_update on public.matches for update to authenticated using (host_user_id=auth.uid()) with check (host_user_id=auth.uid());

-- LINEUPS: host or the assigned team manager.
drop policy if exists lineup_read on public.lineup_submissions;
create policy lineup_read on public.lineup_submissions for select to authenticated using (
 user_id=auth.uid() or exists(select 1 from public.matches m where m.id=match_id and m.host_user_id=auth.uid())
);
drop policy if exists lineup_insert on public.lineup_submissions;
create policy lineup_insert on public.lineup_submissions for insert to authenticated with check (
 user_id=auth.uid() and exists(select 1 from public.tournament_teams tt where tt.id=tournament_team_id and tt.manager_user_id=auth.uid())
);
drop policy if exists lineup_update on public.lineup_submissions;
create policy lineup_update on public.lineup_submissions for update to authenticated using (
 user_id=auth.uid() and exists(select 1 from public.tournament_teams tt where tt.id=tournament_team_id and tt.manager_user_id=auth.uid())
) with check (user_id=auth.uid());

-- MANAGER ACTIONS: manager can submit only for own assigned team; host reads/consumes.
drop policy if exists actions_insert on public.manager_actions;
create policy actions_insert on public.manager_actions for insert to authenticated with check (
 user_id=auth.uid() and exists(select 1 from public.tournament_teams tt where tt.id=tournament_team_id and tt.manager_user_id=auth.uid())
);
drop policy if exists actions_read on public.manager_actions;
create policy actions_read on public.manager_actions for select to authenticated using (
 user_id=auth.uid() or exists(select 1 from public.matches m where m.id=match_id and m.host_user_id=auth.uid())
);
drop policy if exists actions_host_update on public.manager_actions;
create policy actions_host_update on public.manager_actions for update to authenticated using (
 exists(select 1 from public.matches m where m.id=match_id and m.host_user_id=auth.uid())
);

-- EVENTS: host inserts. Public match events are readable; private participants can read.
drop policy if exists events_insert on public.match_events;
create policy events_insert on public.match_events for insert to authenticated with check (
 exists(select 1 from public.matches m where m.id=match_id and m.host_user_id=auth.uid())
);
drop policy if exists events_read on public.match_events;
create policy events_read on public.match_events for select to anon, authenticated using (
 exists(select 1 from public.matches m where m.id=match_events.match_id and (
   m.visibility='public' or m.host_user_id=auth.uid() or exists(
     select 1 from public.tournament_teams tt where tt.tournament_id=m.tournament_id and tt.manager_user_id=auth.uid()
   )
 ))
);

create index if not exists matches_share_code_idx on public.matches(share_code);
create index if not exists match_events_match_id_idx on public.match_events(match_id,id);
create index if not exists manager_actions_match_decision_idx on public.manager_actions(match_id,decision_id,consumed);
