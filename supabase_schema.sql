create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.tournaments (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  local_ref text,
  name text not null,
  visibility text not null default 'public' check (visibility in ('public','private')),
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.tournament_teams (
  id uuid primary key default gen_random_uuid(),
  tournament_id uuid not null references public.tournaments(id) on delete cascade,
  local_team_id text not null,
  team_name text not null,
  squad jsonb not null default '[]'::jsonb,
  manager_user_id uuid references auth.users(id) on delete set null,
  unique(tournament_id, local_team_id)
);

create table if not exists public.manager_invites (
  id uuid primary key default gen_random_uuid(),
  tournament_team_id uuid not null unique references public.tournament_teams(id) on delete cascade,
  invite_code text not null unique,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  claimed_at timestamptz
);

create table if not exists public.matches (
  id uuid primary key default gen_random_uuid(),
  tournament_id uuid references public.tournaments(id) on delete cascade,
  host_user_id uuid not null references auth.users(id) on delete cascade,
  share_code text not null unique,
  team_a_local_id text not null,
  team_b_local_id text not null,
  status text not null default 'lobby' check(status in ('lobby','live','completed','cancelled')),
  visibility text not null default 'public' check(visibility in ('public','private')),
  decision_timeout integer not null default 30,
  state jsonb not null default '{}'::jsonb,
  result jsonb,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.lineup_submissions (
  id uuid primary key default gen_random_uuid(),
  match_id uuid not null references public.matches(id) on delete cascade,
  tournament_team_id uuid not null references public.tournament_teams(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  lineup jsonb not null,
  submitted_at timestamptz not null default now(),
  unique(match_id,tournament_team_id)
);

create table if not exists public.manager_actions (
  id uuid primary key default gen_random_uuid(),
  match_id uuid not null references public.matches(id) on delete cascade,
  tournament_team_id uuid not null references public.tournament_teams(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  decision_id text not null,
  action_type text not null,
  payload jsonb not null,
  consumed boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.match_events (
  id bigint generated by default as identity primary key,
  match_id uuid not null references public.matches(id) on delete cascade,
  ball_no text,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

